import { expect, test } from '@playwright/test';

test('pagina iniziale, inviti e layout responsive', async ({ page }, testInfo) => {
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto('/'); await expect(page.getByRole('heading', { name: /Si laurea uno/ })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: `.checks/home-${testInfo.project.name}.png`, fullPage: true });
  await page.getByRole('button', { name: 'Esplora una demo' }).click();
  await expect(page.getByRole('heading', { name: /Ci siamo/ })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: `.checks/overview-${testInfo.project.name}.png`, fullPage: true });
  await page.getByRole('button', { name: 'Invita gli amici' }).click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await expect(page.getByRole('dialog').locator('svg').first()).toBeVisible();
  await page.keyboard.press('Escape'); await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.getByRole('button', { name: 'Regolamento della partita' }).click();
  await expect(page.getByRole('dialog').getByText('Piange di gioia', { exact: true })).toBeVisible();
  await page.keyboard.press('Escape');
  expect(errors).toEqual([]);
});

test('partita completa, persistenza, punteggi del capitano e annullamento', async ({ page }, testInfo) => {
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto('/demo');
  const nav = page.getByRole('navigation', { name: 'Sezioni della partita' }).filter({ visible: true });
  await nav.getByRole('button', { name: 'Preparazione' }).click();
  await page.getByLabel('Nome del protagonista').fill('Amico speciale');
  await page.getByLabel('Ruolo o soprannome').fill('Compagno di corso');
  await page.getByRole('button', { name: 'Aggiungi protagonista' }).click();
  await expect(page.getByText('Amico speciale', { exact: true })).toBeVisible();
  await page.reload(); await expect(page.getByRole('heading', { name: /Ci siamo/ })).toBeVisible();
  await page.getByRole('button', { name: 'Apri le squadre', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Conferma' }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await nav.getByRole('button', { name: /squadra/i }).click();
  for (const name of ['Mamma Anna', 'Prof. Rossi', 'Luca']) await page.getByRole('button', { name: `Scegli ${name}`, exact: true }).click();
  await page.locator('.team-person').filter({ has: page.getByText('Mamma Anna', { exact: true }) }).getByRole('button', { name: 'Nomina capitano' }).click();
  await page.getByRole('button', { name: 'Salva la squadra' }).click();
  await expect(page.getByText(/La tua squadra è salvata/)).toBeVisible();
  await nav.getByRole('button', { name: 'Regia' }).click();
  await page.getByRole('button', { name: 'Inizia il gioco' }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Conferma' }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.locator('.person-picker').getByRole('button', { name: /Mamma Anna/ }).click();
  await page.getByRole('button', { name: /Piange di gioia/ }).click();
  await expect(page.locator('.diary-row')).toHaveCount(1);
  await page.screenshot({ path: `.checks/control-${testInfo.project.name}.png`, fullPage: true });
  await nav.getByRole('button', { name: 'Classifica' }).click();
  await expect(page.locator('.rank-row.is-me > b')).toHaveText('20PT');
  await nav.getByRole('button', { name: 'Regia' }).click();
  await page.getByRole('button', { name: 'Annulla Piange di gioia a Mamma Anna' }).click();
  await nav.getByRole('button', { name: 'Classifica' }).click();
  await expect(page.locator('.rank-row.is-me > b')).toHaveText('0PT');
  await nav.getByRole('button', { name: 'Panoramica' }).click();
  await page.getByRole('button', { name: 'Concludi la laurea' }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Conferma' }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.getByRole('button', { name: 'Guarda il podio' }).click();
  await expect(page.getByText('LA COMPAGNIA HA IL SUO CAMPIONE')).toBeVisible();
  await page.screenshot({ path: `.checks/final-${testInfo.project.name}.png`, fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect(errors).toEqual([]);
});
